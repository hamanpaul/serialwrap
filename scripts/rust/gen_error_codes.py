#!/usr/bin/env python3
"""由 contracts 生成 sw-proto 的錯誤碼與 session last_error 列舉（P3-T8；arch §3.2、OD-06、SC-34）。

輸入（唯讀，以 PyYAML ``safe_load`` 讀取）：

- ``contracts/error_codes.yaml``：只讀頂層 ``codes`` 序列。每筆產生一個 ``ErrorCode`` variant 與一筆
  ``ErrorCode::META``，順序即 YAML 順序。頂層 ``passthrough`` 等其他區段**不**產生任何 variant
  （SC-34：``last_error`` 不再以 error_code 輸出，故不存在 passthrough／``LastErrorPassthrough`` 變體）。
  ``promoted_via`` 只是資料欄，不影響生成。計數一律來自 YAML，本腳本不寫死任何數字。
- ``contracts/session_last_errors.yaml``：``values`` 序列。``kind: dynamic_prefix``（值為 ``NAME:*``）產生
  帶 ``String`` 原因的動態前綴 variant；其餘為具名 unit variant。``error_code_namespace: forbidden`` 的值
  （目前僅 ``CREDENTIALS_UNRESOLVED``）屬 session 專屬，不得出現在 ``error_codes.yaml``；禁止集合**由本檔資料推導**，
  腳本內不另行硬編。

輸出（生成物，勿手改）：``crates/sw-proto/src/error_codes.rs``、``crates/sw-proto/src/session_last_errors.rs``。

變體名稱以 ``UPPER_SNAKE → UpperCamel`` 產生，並以 ``crates/sw-cli/tests/emitted_codes.rs`` 的
``camel_to_upper_snake`` 反向驗證；不可逆者直接失敗，確保 OD-06 的「會輸出的碼可由常數傳遞路徑抽出」成立。

用法::

    python3 scripts/rust/gen_error_codes.py            # 寫入兩個生成檔
    python3 scripts/rust/gen_error_codes.py --check    # 比對現有檔；不一致則 exit 1 並印 unified diff

退出碼：0＝成功（或 --check 一致）；1＝--check 不一致；2＝輸入缺漏或格式錯誤（含 P0 contracts 未交付）。
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
ERROR_CODES_YAML = ROOT / "contracts" / "error_codes.yaml"
SESSION_LAST_ERRORS_YAML = ROOT / "contracts" / "session_last_errors.yaml"
ERROR_CODES_RS = ROOT / "crates" / "sw-proto" / "src" / "error_codes.rs"
SESSION_LAST_ERRORS_RS = ROOT / "crates" / "sw-proto" / "src" / "session_last_errors.rs"

EXIT_OK = 0
EXIT_MISMATCH = 1
EXIT_INPUT_ERROR = 2

GENERATED_BANNER = "// @generated by scripts/rust/gen_error_codes.py — 勿手改"
SCHEMA_VERSION = 1

CODE_RE = re.compile(r"[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*")
DYNAMIC_VALUE_RE = re.compile(r"([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*):\*")
RUST_IDENT_RE = re.compile(r"[A-Z][A-Za-z0-9]*")

NAMESPACE_FORBIDDEN = "forbidden"
NAMESPACE_VALUES = frozenset({"allowed_shared", NAMESPACE_FORBIDDEN})

# SC-34：``last_error_passthrough`` meta 項已移除；其 code 形式不得再作為 error_code 進入 ErrorCode。
# 採精確名稱比對，不做子字串比對（PASSTHROUGH 子字串可能誤傷其他合法碼）。
SC34_REMOVED_CODES = frozenset({"LAST_ERROR_PASSTHROUGH"})

INTERFACE_VARIANTS = {
    "rpc": "Rpc",
    "rpc_frame": "RpcFrame",
    "cli_client": "CliClient",
    "cli_local": "CliLocal",
    "rec": "Rec",
    "proc": "Proc",
}
RETRYABLE_VARIANTS = {"yes": "Yes", "no": "No", "conditional": "Conditional", "fix_args": "FixArgs"}
STATUS_VARIANTS = {
    "EXISTING": "Existing",
    "APPROVED": "Approved",
    "IMPLEMENTED": "Implemented",
    "VERIFIED": "Verified",
}


class GenError(Exception):
    """輸入缺漏或格式不合規（exit 2）。"""


class P0MissingError(GenError):
    """P0 contracts 未交付（exit 2；不 SKIP）。"""


@dataclass(frozen=True)
class ErrorCodeEntry:
    code: str
    variant: str
    interfaces: tuple[str, ...]
    retryable: str
    reachable: bool
    status: str
    meaning: str


@dataclass(frozen=True)
class SessionEntry:
    value: str  # 具名值全文；動態前綴為不含 ":*" 的前綴
    dynamic: bool
    variant: str
    reachable: bool
    meaning: str
    namespace: str  # error_code_namespace：allowed_shared 或 forbidden


def _camel_to_upper_snake(name: str) -> str:
    """與 ``crates/sw-cli/tests/emitted_codes.rs::camel_to_upper_snake`` 逐字對齊（OD-06 抽取規則）。"""
    out: list[str] = []
    for i, ch in enumerate(name):
        if ch.isupper():
            if i > 0:
                prev = name[i - 1]
                nxt = name[i + 1] if i + 1 < len(name) else ""
                prev_not_upper = not prev.isupper()
                next_is_lower = nxt != "" and nxt.islower()
                if prev_not_upper or (prev.isupper() and next_is_lower):
                    out.append("_")
            out.append(ch)
        else:
            out.append(ch.upper())
    return "".join(out)


def _upper_camel(name: str) -> str:
    """UPPER_SNAKE → UpperCamel，並驗證可反向還原（否則 OD-06 抽取會對不上）。"""
    variant = "".join(seg.capitalize() for seg in name.split("_"))
    if not RUST_IDENT_RE.fullmatch(variant):
        raise GenError(f"{name!r} 無法產生合法的 Rust 變體名（得到 {variant!r}）")
    if _camel_to_upper_snake(variant) != name:
        raise GenError(f"{name!r} → {variant!r} 無法反向還原為原碼（OD-06 抽取規則不相容）")
    return variant


def _load_yaml(path: Path) -> Any:
    if not path.is_file():
        raise P0MissingError(f"P0 contracts 未交付，證據不足：{path.relative_to(ROOT)}")
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise GenError(f"{path.name} 解析失敗：{exc}") from exc


def _check_schema(doc: Any, name: str) -> dict[str, Any]:
    if not isinstance(doc, dict):
        raise GenError(f"{name} 頂層必須為 mapping")
    if doc.get("schema_version") != SCHEMA_VERSION:
        raise GenError(f"{name} schema_version 不支援：{doc.get('schema_version')!r}")
    revision = doc.get("revision")
    if not isinstance(revision, int) or isinstance(revision, bool):
        raise GenError(f"{name} 缺少整數 revision")
    return doc


def _parse_error_codes(doc: Any, forbidden: frozenset[str] = frozenset()) -> tuple[int, list[ErrorCodeEntry]]:
    """解析 error_codes.yaml 的 ``codes``。``forbidden`` 為 session 命名空間禁止進入本檔的碼（由 session YAML 推導）。"""
    root = _check_schema(doc, "error_codes.yaml")
    items = root.get("codes")
    if not isinstance(items, list) or not items:
        raise GenError("error_codes.yaml 缺少非空 codes 序列")
    entries: list[ErrorCodeEntry] = []
    seen: set[str] = set()
    for idx, item in enumerate(items):
        where = f"error_codes.yaml codes[{idx}]"
        if not isinstance(item, dict):
            raise GenError(f"{where} 必須為 mapping")
        code = item.get("code")
        if not isinstance(code, str) or not CODE_RE.fullmatch(code):
            raise GenError(f"{where}.code 格式不合法：{code!r}")
        if code in seen:
            raise GenError(f"重複的 code：{code}")
        seen.add(code)
        if code in SC34_REMOVED_CODES:
            raise GenError(f"{code}：SC-34 已移除 last_error_passthrough，不得再作為 error_code 進入 ErrorCode")
        if code in forbidden:
            raise GenError(
                f"{code} 在 session_last_errors.yaml 標為 error_code_namespace: {NAMESPACE_FORBIDDEN}"
                "（session 專屬），不得列於 error_codes.yaml"
            )
        status = item.get("status")
        if status not in STATUS_VARIANTS:
            raise GenError(f"{code}.status 不合法：{status!r}")
        retryable = item.get("retryable")
        if retryable not in RETRYABLE_VARIANTS:
            raise GenError(f"{code}.retryable 不合法：{retryable!r}")
        reachable = item.get("reachable")
        if not isinstance(reachable, bool):
            raise GenError(f"{code}.reachable 必須為 bool")
        scope = item.get("scope")
        interfaces = scope.get("interfaces") if isinstance(scope, dict) else None
        if not isinstance(interfaces, list) or not interfaces:
            raise GenError(f"{code}.scope.interfaces 必須為非空序列")
        for iface in interfaces:
            if iface not in INTERFACE_VARIANTS:
                raise GenError(f"{code}.scope.interfaces 含未知介面：{iface!r}")
        meaning = item.get("meaning", "")
        if not isinstance(meaning, str):
            raise GenError(f"{code}.meaning 必須為字串")
        entries.append(
            ErrorCodeEntry(
                code=code,
                variant=_upper_camel(code),
                interfaces=tuple(INTERFACE_VARIANTS[i] for i in interfaces),
                retryable=RETRYABLE_VARIANTS[retryable],
                reachable=reachable,
                status=STATUS_VARIANTS[status],
                meaning=meaning,
            )
        )
    if not entries:
        raise GenError("error_codes.yaml 沒有任何 code")
    return int(root["revision"]), entries


def _parse_session_last_errors(doc: Any) -> tuple[int, list[SessionEntry]]:
    root = _check_schema(doc, "session_last_errors.yaml")
    items = root.get("values")
    if not isinstance(items, list) or not items:
        raise GenError("session_last_errors.yaml 缺少非空 values 序列")
    entries: list[SessionEntry] = []
    seen_values: set[str] = set()
    seen_variants: set[str] = set()
    for idx, item in enumerate(items):
        where = f"session_last_errors.yaml values[{idx}]"
        if not isinstance(item, dict):
            raise GenError(f"{where} 必須為 mapping")
        raw = item.get("value")
        if not isinstance(raw, str):
            raise GenError(f"{where}.value 必須為字串")
        kind = item.get("kind", "named")
        if kind == "named":
            if not CODE_RE.fullmatch(raw):
                raise GenError(f"{where}.value 格式不合法：{raw!r}")
            dynamic = False
            name = raw
        elif kind == "dynamic_prefix":
            matched = DYNAMIC_VALUE_RE.fullmatch(raw)
            if not matched:
                raise GenError(f"{where}.value 動態前綴須為 NAME:*，得到 {raw!r}")
            dynamic = True
            name = matched.group(1)
        else:
            raise GenError(f"{where}.kind 不合法：{kind!r}")
        if name in seen_values:
            raise GenError(f"重複的 session last_error 值：{name}")
        seen_values.add(name)
        variant = _upper_camel(name)
        if variant in seen_variants:
            raise GenError(f"session last_error 變體名重複：{variant}")
        seen_variants.add(variant)
        reachable = item.get("reachable")
        if not isinstance(reachable, bool):
            raise GenError(f"{where}.reachable 必須為 bool")
        meaning = item.get("meaning", "")
        if not isinstance(meaning, str):
            raise GenError(f"{where}.meaning 必須為字串")
        namespace = item.get("error_code_namespace")
        if namespace not in NAMESPACE_VALUES:
            raise GenError(f"{where}.error_code_namespace 不合法：{namespace!r}")
        entries.append(
            SessionEntry(
                value=name,
                dynamic=dynamic,
                variant=variant,
                reachable=reachable,
                meaning=meaning,
                namespace=namespace,
            )
        )
    return int(root["revision"]), entries


_DOC_ESCAPE_RE = re.compile(r"([\\\[\]<])")


def _escape_doc_line(text: str) -> str:
    """讓 rustdoc 逐字呈現說明文字：反斜線、方括號與小於號加反斜線跳脫，避免被當成 intra-doc link 或未閉合 HTML。"""
    return _DOC_ESCAPE_RE.sub(r"\\\1", text)


def _doc_comment(text: str, indent: str, extra: str | None = None) -> list[str]:
    lines = [_escape_doc_line(ln.strip()) for ln in text.strip().splitlines()]
    if extra:
        lines.append(extra)
    return [f"{indent}///" if not ln else f"{indent}/// {ln}" for ln in lines]


_INTERFACE_AND_STATUS_TYPES = """\
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Interface {
    Rpc,
    RpcFrame,
    CliClient,
    CliLocal,
    Rec,
    Proc,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Retryable {
    Yes,
    No,
    Conditional,
    FixArgs,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    Existing,
    Approved,
    Implemented,
    Verified,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ErrorMeta {
    pub code: &'static str,
    pub interfaces: &'static [Interface],
    pub retryable: Retryable,
    pub reachable: bool,
    pub status: Status,
}
"""


def render_error_codes(revision: int, entries: list[ErrorCodeEntry]) -> str:
    out: list[str] = [
        GENERATED_BANNER,
        f"// 來源：contracts/error_codes.yaml（revision {revision}）；改 YAML 後重跑 scripts/rust/gen_error_codes.py。",
        "//! RPC／CLI `error_code` 命名空間（arch §3.2）。",
        "//!",
        "//! 變體與 `ErrorCode::META` 依 YAML `codes` 順序生成；頂層 `passthrough` 區段不產生任何變體（SC-34）。",
        "",
        "/// 每個碼一個 variant（由 `contracts/error_codes.yaml` 生成）。",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum ErrorCode {",
    ]
    for e in entries:
        out += _doc_comment(e.meaning, "    ")
        out.append(f"    {e.variant},")
    out += ["}", "", _INTERFACE_AND_STATUS_TYPES.rstrip("\n"), "", "impl ErrorCode {"]

    out.append("    /// 依 YAML 順序的完整目錄；`meta()` 以判別值索引，故順序與 variant 宣告順序一致。")
    out.append("    pub const META: &'static [ErrorMeta] = &[")
    for e in entries:
        out += [
            "        ErrorMeta {",
            f"            code: {_rust_str(e.code)},",
            f"            interfaces: &[{', '.join('Interface::' + i for i in e.interfaces)}],",
            f"            retryable: Retryable::{e.retryable},",
            f"            reachable: {'true' if e.reachable else 'false'},",
            f"            status: Status::{e.status},",
            "        },",
        ]
    out.append("    ];")
    out.append("")

    out.append("    /// 回傳 YAML 中的碼字串（與 `contracts/error_codes.yaml` 的 `code` 欄位逐字相同）。")
    out.append("    pub fn as_str(self) -> &'static str {")
    out.append("        match self {")
    for e in entries:
        out += _arm(f"ErrorCode::{e.variant}", _rust_str(e.code), "            ")
    out.append("        }")
    out.append("    }")
    out.append("")

    out.append("    /// 由碼字串還原 variant；未知字串（含 session 命名空間的 CREDENTIALS_UNRESOLVED）回 `None`。")
    out.append("    pub fn parse(s: &str) -> Option<ErrorCode> {")
    out.append("        match s {")
    for e in entries:
        out += _arm(_rust_str(e.code), f"Some(ErrorCode::{e.variant})", "            ")
    out.append("            _ => None,")
    out.append("        }")
    out.append("    }")
    out.append("")

    out.append("    /// 取得該碼的目錄資料。")
    out.append("    pub fn meta(self) -> &'static ErrorMeta {")
    out.append("        &Self::META[self as usize]")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def render_session_last_errors(revision: int, entries: list[SessionEntry]) -> str:
    named = [e for e in entries if not e.dynamic]
    dynamic = [e for e in entries if e.dynamic]
    out: list[str] = [
        GENERATED_BANNER,
        f"// 來源：contracts/session_last_errors.yaml（revision {revision}）；改 YAML 後重跑 scripts/rust/gen_error_codes.py。",
        "//! session `last_error` 命名空間（arch §3.2；與 `ErrorCode` 互不轉換）。",
        "//!",
        "//! 具名值依 YAML `values` 順序生成為 unit variant；動態前綴（`NAME:*`）生成為帶原因字串的 tuple variant。",
        "",
        "#[derive(Clone, Debug, PartialEq, Eq)]",
        "pub enum SessionLastError {",
    ]
    for e in entries:
        extra = None if e.reachable else "（reachable:false）"
        out += _doc_comment(e.meaning, "    ", extra)
        if e.dynamic:
            out.append(f"    {e.variant}(String),")
        else:
            out.append(f"    {e.variant},")
    out += ["}", "", "impl SessionLastError {"]

    out.append("    /// 回應與 CLI 顯示用的字串形式；動態前綴為 `PREFIX:<原因>`。")
    out.append("    pub fn as_string(&self) -> String {")
    out.append("        match self {")
    for e in named:
        out += _arm(f"SessionLastError::{e.variant}", f"{_rust_str(e.value)}.to_string()", "            ")
    for e in dynamic:
        out += _arm(
            f"SessionLastError::{e.variant}(reason)",
            f"format!({_rust_str(e.value + ':{reason}')})",
            "            ",
        )
    out.append("        }")
    out.append("    }")
    out.append("")

    out.append("    /// 由字串還原；具名值精確比對，動態前綴須為 `PREFIX:` 後接非空原因（`*` 對應 `<ExcClassName>`）。")
    out.append("    pub fn parse(s: &str) -> Option<SessionLastError> {")
    out.append("        match s {")
    for e in named:
        out += _arm(_rust_str(e.value), f"Some(SessionLastError::{e.variant})", "            ")
    out.append("            _ => {")
    out.append("                let (prefix, reason) = s.split_once(':')?;")
    out.append("                if reason.is_empty() {")
    out.append("                    return None;")
    out.append("                }")
    out.append("                let reason = reason.to_string();")
    out.append("                match prefix {")
    for e in dynamic:
        out += _arm(_rust_str(e.value), f"Some(SessionLastError::{e.variant}(reason))", "                    ")
    out.append("                    _ => None,")
    out.append("                }")
    out.append("            }")
    out.append("        }")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def _arm(pattern: str, expr: str, indent: str) -> list[str]:
    """產生一個 match arm；單行放得下（≤100 欄，rustfmt 預設）就單行，否則改區塊形式，與 rustfmt 輸出一致。"""
    single = f"{indent}{pattern} => {expr},"
    if len(single) <= 100:
        return [single]
    return [f"{indent}{pattern} => {{", f"{indent}    {expr}", f"{indent}}}"]


def _rust_str(text: str) -> str:
    """Rust 字串字面值（本生成器的輸入皆為 ASCII 碼名，僅需跳脫反斜線與雙引號）。"""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _force_utf8_stdio() -> None:
    """固定 stdout／stderr 為 UTF-8、LF：Windows 預設 code page（如 cp1252）無法編碼繁中輸出（比照 check_cfg_boundary.py）。"""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", newline="\n")


def build_outputs() -> dict[Path, str]:
    sess_rev, sess_entries = _parse_session_last_errors(_load_yaml(SESSION_LAST_ERRORS_YAML))
    forbidden = frozenset(e.value for e in sess_entries if e.namespace == NAMESPACE_FORBIDDEN)
    err_rev, err_entries = _parse_error_codes(_load_yaml(ERROR_CODES_YAML), forbidden)
    return {
        ERROR_CODES_RS: render_error_codes(err_rev, err_entries),
        SESSION_LAST_ERRORS_RS: render_session_last_errors(sess_rev, sess_entries),
    }


def _rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def main(argv: list[str] | None = None) -> int:
    _force_utf8_stdio()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--check",
        action="store_true",
        help="只比對現有生成檔；不一致則 exit 1 並印 unified diff（不寫檔）",
    )
    args = parser.parse_args(argv)

    try:
        outputs = build_outputs()
    except P0MissingError as exc:
        print(str(exc), file=sys.stderr)
        return EXIT_INPUT_ERROR
    except GenError as exc:
        print(f"gen_error_codes: {exc}", file=sys.stderr)
        return EXIT_INPUT_ERROR

    if not args.check:
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"寫入 {_rel(path)}")
        return EXIT_OK

    mismatched = False
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current == text:
            continue
        mismatched = True
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            text.splitlines(keepends=True),
            fromfile=f"{_rel(path)}（現有）",
            tofile=f"{_rel(path)}（生成）",
        )
        sys.stdout.writelines(diff)
        if not current:
            print(f"gen_error_codes: 缺少生成檔 {_rel(path)}", file=sys.stderr)
    if mismatched:
        print("gen_error_codes --check: 生成檔與 contracts 不一致；請重跑 scripts/rust/gen_error_codes.py", file=sys.stderr)
        return EXIT_MISMATCH
    print("gen_error_codes --check: OK")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
